"""Generate ``docs/data-dictionary.md`` from the models that define the data.

Every column's meaning is written once, as a ``description`` on the field of
the model that defines it (``models/scrape.py``, ``models/parsed.py``,
``models/clean.py``); types and checks come from the same models and the
store schemas. A test fails when the file is out of date, so run this after
changing a model:

    uv run python scripts/generate_data_dictionary.py
"""

