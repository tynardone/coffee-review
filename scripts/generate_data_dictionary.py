def render() -> str:
    """The whole data dictionary as Markdown."""
    sections = [
        _intro(),
        "## Raw layer: `data/raw/`",
        (
            "Saved pages are gzipped HTML at `reviews/<slug>.html.gz`. The manifest"
            " records what is known about each review."
        ),
        _pydantic_table(
            "`manifest.sqlite`, table `reviews`",
            "One row per review the sitemaps have listed. Written by `scrape`.",
            ManifestRecord,
        ),
        _files_table(
            "Reference responses: `data/raw/fx/`, `data/raw/cpi/`",
            (
                "Written by `fx` and `cpi`. The tidy reference tables are rebuilt from"
                " these on every run (ADR 0009)."
            ),
            RAW_REFERENCE,
        ),
        "## Parsed layer: `data/parsed/`",
        (
            "Every value is text, exactly as the page had it (ADR 0007). Written by"
            " `parse`, read by `clean`."
        ),
        _parsed_table("roasted", RoastedReview),
        _parsed_table("green", GreenReview),
        _plain_table(
            "`roasted/extra_fields.parquet`, `green/extra_fields.parquet`",
            "Labels and headings the parser didn't recognise, kept as found.",
            [(name, "String", "no", text) for name, text in EXTRA_FIELDS.items()],
        ),
        _pydantic_table(
            "`parse_issues.parquet`",
            "Pages worth a look. Never stops a run.",
            ParseIssue,
        ),
        "## Clean layer: `data/clean/`",
        (
            "Typed columns, checked against the contract in `models/clean.py` on every"
            " run (Decisions 1–11 in the M3 design). Written by `clean`."
        ),
        _pandera_table(
            "`roasted/reviews.parquet`",
            "One row per roasted review (espresso included).",
            CleanRoastedFrame,
        ),
        _pandera_table(
            "`green/reviews.parquet`", "One row per green review.", CleanGreenFrame
        ),
        _pandera_table(
            "`cleaning_log.parquet`",
            "One row for every rule applied to a value, with the original text.",
            CleanLogFrame,
        ),
        _rules_table(),
        "## Reference layer: `data/reference/`",
        (
            "Exchange rates and US CPI for M5 to convert and adjust prices with."
            " Rebuilt in full from the saved responses and checked against the"
            " contracts in `models/reference.py` on every run. Written by `fx` and"
            " `cpi`. A period the source has no data for (October 2025's CPI) is"
            " simply absent."
        ),
        _pandera_table(
            "`fx.parquet`",
            "One row per day (the 1st of each month) and currency.",
            FxFrame,
        ),
        _pandera_table("`cpi.parquet`", "One row per series and month.", CpiFrame),
        "## Lookup tables: `src/coffee_review/transforms/lookups/`",
        (
            "Versioned with the code. A table gains a row when the clean report"
            " lists a real place, currency or unit it doesn't know."
        ),
        *(_lookup_table(name, *spec) for name, spec in LOOKUPS.items()),
    ]
    return "\n\n".join(sections) + "\n"


def _intro() -> str:
    return (
        "# Data dictionary\n\n"
        "<!-- Generated by scripts/generate_data_dictionary.py from the models."
        " Don't edit by hand: change the model's description and regenerate. -->\n\n"
        "Every table the pipeline writes, layer by layer, and the lookup tables"
        " that drive cleaning. For how the layers connect, see"
        " [architecture.md](architecture.md).\n\n"
        "| Layer | Where | Written by |\n|---|---|---|\n"
        "| Raw | `data/raw/` | `coffee-review scrape` |\n"
        "| Parsed | `data/parsed/` | `coffee-review parse` |\n"
        "| Clean | `data/clean/` | `coffee-review clean` |\n"
        "| Reference | `data/reference/` (responses in `data/raw/`) |"
        " `coffee-review fx`, `coffee-review cpi` |"
    )


def _plain_table(title: str, about: str, rows: list[tuple[str, str, str, str]]) -> str:
    lines = [
        f"### {title}",
        "",
        about,
        "",
        "| Column | Type | Can be empty | Meaning |",
    ]
    lines.append("|---|---|---|---|")
    lines += [f"| `{c}` | {t} | {e} | {_cell(m)} |" for c, t, e, m in rows]
    return "\n".join(lines)


def _files_table(title: str, about: str, files: dict[str, str]) -> str:
    lines = [f"### {title}", "", about, "", "| File | What it holds |", "|---|---|"]
    lines += [f"| `{name}` | {_cell(text)} |" for name, text in files.items()]
    return "\n".join(lines)


def _pydantic_table(title: str, about: str, model: type[BaseModel]) -> str:
    rows = [
        (
            name,
            _python_type(field.annotation),
            _empty(field.annotation),
            field.description or "",
        )
        for name, field in model.model_fields.items()
    ]
    return _plain_table(title, about, rows)


def _parsed_table(dataset: str, model: type[BaseModel]) -> str:
    schema = reviews_frame([], dataset).schema  # type: ignore[arg-type]
    rows = []
    for name, dtype in schema.items():
        if name == "extra_count":
            rows.append((name, str(dtype), "no", EXTRA_COUNT))
            continue
        field = model.model_fields[name]
        rows.append(
            (name, str(dtype), _empty(field.annotation), field.description or "")
        )
    return _plain_table(
        f"`{dataset}/reviews.parquet`",
        f"One row per {dataset} review, values as text.",
        rows,
    )


def _pandera_table(title: str, about: str, model: type[pa.DataFrameModel]) -> str:
    lines = [f"### {title}", "", about, ""]
    key = model.to_schema().unique
    if key:
        names = ", ".join(f"`{name}`" for name in key)
        lines += [f"Key: each ({names}) appears once.", ""]
    lines += [
        "| Column | Type | Can be empty | Checks | Meaning |",
        "|---|---|---|---|---|",
    ]
    for name, column in model.to_schema().columns.items():
        checks = [_check(c) for c in column.checks]
        if column.unique:
            checks.insert(0, "unique")
        empty = "yes" if column.nullable else "no"
        lines.append(
            f"| `{name}` | {_polars_type(column.dtype)} | {empty}"
            f" | {', '.join(checks) or '–'} | {_cell(column.description or '')} |"
        )
    return "\n".join(lines)


def _rules_table() -> str:
    lines = [
        "### Cleaning rules",
        "",
        "The values of `cleaning_log.rule`: every change the clean stage makes.",
        "",
        "| Rule | Meaning |",
        "|---|---|",
    ]
    lines += [
        f"| `{rule}` | {_cell(text)} |" for rule, text in RULE_DESCRIPTIONS.items()
    ]
    return "\n".join(lines)


def _lookup_table(name: str, about: str, columns: dict[str, str]) -> str:
    text = files("coffee_review.transforms.lookups").joinpath(name).read_text("utf-8")
    header = next(csv.reader(text.splitlines()))
    rows = len(text.splitlines()) - 1
    assert header == list(columns), (name, header)  # the dictionary must match
    lines = [f"### `{name}` ({rows:,} rows)", "", about, "", "| Column | Meaning |"]
    lines.append("|---|---|")
    lines += [f"| `{c}` | {_cell(m)} |" for c, m in columns.items()]
    return "\n".join(lines)


def _check(check: Any) -> str:
    stats = check.statistics
    match check.name:
        case "greater_than_or_equal_to":
            return f"≥ {stats['min_value']}"
        case "less_than_or_equal_to":
            return f"≤ {stats['max_value']}"
        case "greater_than":
            return f"> {stats['min_value']}"
        case "str_matches":
            return f"matches `{stats['pattern']}`"
        case "isin" if len(stats["allowed_values"]) > 5:
            return "one of the cleaning rules"
        case "isin":
            return "one of " + ", ".join(f"`{v}`" for v in stats["allowed_values"])
        case "first_of_month":
            return "always the 1st"
        case _:
            return str(check.name)


def _polars_type(dtype: Any) -> str:
    text = str(dtype)
    return "Enum (6 roast levels)" if text.startswith("Enum") else text


def _python_type(annotation: Any) -> str:
    args = [a for a in typing.get_args(annotation) if a is not type(None)]
    if _is_optional(annotation) and len(args) == 1:
        return _python_type(args[0])
    if typing.get_origin(annotation) is typing.Literal:
        return " / ".join(f"`{a}`" for a in typing.get_args(annotation))
    base = typing.get_origin(annotation) or annotation
    if isinstance(annotation, typing.TypeAliasType):
        return _python_type(annotation.__value__)
    if typing.get_origin(annotation) is typing.Annotated:
        return _python_type(typing.get_args(annotation)[0])
    names = {str: "text", bool: "true/false", int: "integer", float: "decimal"}
    if base is datetime:
        return "datetime (UTC)"
    return names.get(base, getattr(base, "__name__", str(base)))


def _is_optional(annotation: Any) -> bool:
    origin = typing.get_origin(annotation)
    return origin in (typing.Union, types.UnionType) and type(None) in typing.get_args(
        annotation
    )


def _empty(annotation: Any) -> str:
    return "yes" if _is_optional(annotation) else "no"


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def main() -> None:
    OUT.write_text(render(), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
